// Writes Assets/Scripts/BuildAliveWorkspaceSnapshot.ts from the running bridge (GET /workspace).
// The Lens cannot reach the bridge from Preview without Experimental APIs, so the REAL scan result is bundled as a snapshot.
// usage: node devpost/tools/gen-workspace-snapshot.mjs [http://127.0.0.1:8787]
import fs from "node:fs"
import path from "node:path"
import {fileURLToPath} from "node:url"

const base = process.argv[2] || "http://127.0.0.1:8787"
const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.join(here, "..", "..", "Assets", "Scripts", "BuildAliveWorkspaceSnapshot.ts")

const res = await fetch(base + "/workspace")
if (!res.ok) throw new Error("bridge /workspace failed: " + res.status)
const payload = await res.json()
if (payload.type !== "workspace" || !Array.isArray(payload.worlds) || payload.worlds.length === 0) throw new Error("unexpected /workspace payload")

const scannedAt = new Date().toISOString()
const body = `// GENERATED by devpost/tools/gen-workspace-snapshot.mjs - do not edit by hand.
// REAL scan of approved git repositories (bridge/project-discovery.mjs, GET /workspace), bundled because the Lens cannot
// open ws://127.0.0.1 in Preview unless Lens Studio Experimental APIs is enabled. This is a SNAPSHOT, not a live feed.
export const WORKSPACE_SNAPSHOT_META = {
  scannedAt: ${JSON.stringify(scannedAt)},
  source: "bridge/project-discovery.mjs GET /workspace",
  worlds: ${JSON.stringify(payload.worlds.map((w) => ({projectId: w.projectId, name: w.name, branch: w.branch, head: w.head, fileCount: w.fileCount})))},
}
export const WORKSPACE_SNAPSHOT: unknown = ${JSON.stringify({type: "workspace", worlds: payload.worlds}, null, 1)}
`
fs.writeFileSync(out, body)
console.log("wrote", out, body.length, "bytes;", payload.worlds.map((w) => w.name + "@" + w.head).join(", "))
